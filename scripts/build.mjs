#!/usr/bin/env node
/* =========================================================
   scripts/build.mjs — static page generator (build time only).

   Reads config/ and data/ and writes the committed, ready-to-serve HTML:
     index.html
     categories/<id>/index.html     one per LIVE category
     about/ privacy/ terms/ index.html
     sitemap.xml
   and refreshes the JSON-LD block inside each live wish page
   (between <!-- build:jsonld --> markers).

   Cloudflare Pages needs NO build: the output is committed. Run this
   after changing anything in data/, config/ or scripts/lib/.

   Usage:
     node scripts/build.mjs           write files
     node scripts/build.mjs --check   exit 1 if any generated file is stale
   ========================================================= */
import fs from "node:fs";
import path from "node:path";
import { ROOT, loadSite } from "./lib/load.mjs";
import { buildModel, breadcrumbLd, siteLd } from "./lib/components.mjs";
import { homePage, categoryPage, contentPage, contentKeys } from "./lib/pages.mjs";
import { creatorPage } from "./lib/creator-page.mjs";
import { jsonLd } from "./lib/html.mjs";

const check = process.argv.includes("--check");
const model = buildModel(loadSite());
const { config, live, catById } = model;
const site = config.siteUrl;

const outputs = [];
outputs.push(homePage(model));
for (const cat of model.liveCategories) outputs.push(categoryPage(model, cat));
if (model.creatorTemplates.length) outputs.push(creatorPage(model));
for (const key of contentKeys) outputs.push(contentPage(model, key));

/* ---- sitemap: every implemented, indexable page ---- */
const urls = [
  ...outputs.map((o) => o.path),
  ...live.map((w) => w.route)
];
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<!--
  GENERATED by \`node scripts/build.mjs\` — do not edit by hand.
  Lists only pages that exist (homepage, live categories, live wishes,
  /create/, About / Privacy / Terms). Replace SITE_URL_PLACEHOLDER — see README.md.
-->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map((u) => `  <url>\n    <loc>${site}${u}</loc>\n  </url>`).join("\n")}
</urlset>
`;
outputs.push({ file: "sitemap.xml", html: sitemap });

/* ---- wish pages: refresh the JSON-LD block ---- */
const OPEN = "<!-- build:jsonld -->";
const CLOSE = "<!-- /build:jsonld -->";
for (const w of live) {
  const cat = catById[w.category];
  const crumbs = [
    { label: { bn: model.data.ui.crumbHome.bn, en: model.data.ui.crumbHome.en }, path: "/" },
    { label: cat.pageTitle, path: `/categories/${cat.id}/` },
    { label: w.title, path: w.route }
  ];
  const graph = {
    "@context": "https://schema.org",
    "@graph": [
      siteLd(model),
      {
        "@type": "WebPage",
        "@id": `${site}${w.route}#webpage`,
        url: `${site}${w.route}`,
        name: w.title.en,
        description: w.description.en,
        isPartOf: { "@id": `${site}/#website` },
        inLanguage: w.languages,
        breadcrumb: { "@id": `${site}${w.route}#breadcrumb` }
      },
      { ...breadcrumbLd(model, crumbs), "@id": `${site}${w.route}#breadcrumb` }
    ]
  };
  const file = path.join(ROOT, w.path);
  const src = fs.readFileSync(file, "utf8");
  const a = src.indexOf(OPEN);
  const b = src.indexOf(CLOSE);
  if (a === -1 || b === -1) {
    console.error(`ERROR ${w.path}: missing ${OPEN} … ${CLOSE} markers`);
    process.exit(1);
  }
  outputs.push({ file: w.path, html: src.slice(0, a + OPEN.length) + "\n" + jsonLd(graph) + "\n" + src.slice(b) });
}

/* ---- write / check ---- */
let stale = 0;
for (const o of outputs) {
  const dest = path.join(ROOT, o.file);
  const current = fs.existsSync(dest) ? fs.readFileSync(dest, "utf8") : null;
  if (current === o.html) continue;
  stale++;
  if (check) {
    console.error(`STALE ${o.file}`);
  } else {
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, o.html);
    console.log(`wrote ${o.file}`);
  }
}
if (check) {
  if (stale) { console.error(`${stale} generated file(s) out of date — run: node scripts/build.mjs`); process.exit(1); }
  console.log(`OK — ${outputs.length} generated files are up to date.`);
} else {
  console.log(stale ? `Done (${stale} file(s) written).` : "Nothing to do — all generated files already up to date.");
}

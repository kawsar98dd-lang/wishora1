/* ---------------------------------------------------------
   CATEGORY (one page per LIVE category)
--------------------------------------------------------- */
export function categoryPage(m, cat) {
  const { i18n: { t, bi, tx }, config, data } = m;
  const site = config.siteUrl;
  const path = categoryUrl(cat.id);
  const wishes = wishesOf(m, cat.id);

  const title = `${joinTitle(m, cat.pageTitle)} — Wishora`;
  const description = m.langs.map((l) => cat.meta[l]).reverse().join(" · ");

  const crumbs = [
    { label: { bn: tx("crumbHome", "bn"), en: tx("crumbHome", "en") }, href: "/", path: "/" },
    { label: cat.pageTitle, path }
  ];

  /* "Make it personal": only when the wish template really takes name+from. */
  const first = wishes[0];
  const tpl = data.templates.find((x) => x.id === first.template);
  const pnames = (tpl?.fields || []).map((x) => x.param);
  const canPersonalise = pnames.includes("name") && pnames.includes("from");
  const exampleQuery = "?name=Anika&from=Rafi";

  const related = (cat.related || [])
    .map((id) => m.catById[id])
    .filter((c) => c && (m.liveCatIds.has(c.id) || m.soonCategories.includes(c)));

  const body = `<main id="main-content">
  <section class="page-hero">
    <div class="hero-glow hero-glow-a" aria-hidden="true"></div>
    <div class="container">
      ${breadcrumb(m, crumbs)}
      <p class="page-icon" aria-hidden="true">${esc(cat.icon)}</p>
      <h1 class="page-title">${bi(cat.pageTitle)}</h1>
      <p class="page-lead">${bi(cat.description)}</p>
      <div class="page-intro">
${m.langs.map((l, i) => cat.intro[l].map((para) => `        <p data-l="${l}" lang="${l}">${esc(para)}</p>`).join("\n")).join("\n")}
      </div>
    </div>
  </section>

  <section class="cat-wishes" aria-labelledby="wishes-title">
    <div class="container">
      <h2 class="block-title" id="wishes-title">${t("catWishesTitle")}</h2>
      <ul class="wish-grid">
${wishes.map((w) => wishCard(m, w, 3)).join("\n")}
      </ul>
    </div>
  </section>
${Array.isArray(cat.faq) && cat.faq.length ? `
  <section class="category-faq" aria-labelledby="category-faq-title">
    <div class="container category-faq-inner">
      <h2 class="block-title" id="category-faq-title">${t("catFaqTitle")}</h2>
      <p class="category-faq-intro">${t("catFaqIntro")}</p>
      <div class="faq-list">
${cat.faq.map((item, index) => `        <details class="faq-item"${index === 0 ? " open" : ""}>
          <summary>${bi(item.q)}</summary>
          <div class="faq-answer">${m.langs.map((l) => `<p data-l="${l}" lang="${l}">${esc(item.a[l])}</p>`).join("")}</div>
        </details>`).join("\n")}
      </div>
    </div>
  </section>
` : ""}
${canPersonalise ? `
  <section class="howto" aria-labelledby="howto-title">
    <div class="container">
      <h2 class="block-title" id="howto-title">${t("catHowTitle")}</h2>
      <p class="howto-text">${t("catHowText")}</p>
      <p class="howto-code"><code>…${esc(first.route + exampleQuery)}</code></p>
      <p><a class="text-link" href="${esc(first.route + exampleQuery)}">${t("catHowExample")} →</a></p>
    </div>
  </section>
` : ""}
  ${adSlot("AD_SLOT_CONTENT")}
${related.length ? `
  <section class="other" aria-labelledby="other-title">
    <div class="container">
      <h2 class="block-title" id="other-title">${t("catOtherTitle")}</h2>
      <p class="howto-text">${t("catOtherText")}</p>
      <ul class="cat-grid">
${related.map((c) => categoryCard(m, c)).join("\n")}
      </ul>
    </div>
  </section>
` : ""}
  <section class="final-cta" aria-labelledby="cta-title">
    <div class="container final-cta-inner">
      <h2 id="cta-title">${t("catCreateTitle")}</h2>
      <p>${t("creatorText")}</p>
      <div class="cta-row">
        ${m.creatorCatIds.has(cat.id) ? `<a href="/create/?category=${esc(cat.id)}" class="btn btn-light btn-large">${t("createCta")}</a>` : ""}
        <a href="/#explore" class="btn btn-ghost-light btn-large">${t("catBackAll")}</a>
      </div>
    </div>
  </section>
  ${adSlot("AD_SLOT_BOTTOM")}
</main>`;

  const jsonld = {
    "@context": "https://schema.org",
    "@graph": [
      siteLd(m),
      {
        "@type": "CollectionPage",
        "@id": `${site}${path}#webpage`,
        url: `${site}${path}`,
        name: cat.pageTitle.en,
        description: cat.meta.en,
        isPartOf: { "@id": `${site}/#website` },
        inLanguage: m.langs,
        breadcrumb: { "@id": `${site}${path}#breadcrumb` }
      },
      { ...breadcrumbLd(m, crumbs), "@id": `${site}${path}#breadcrumb` },
      ...(Array.isArray(cat.faq) && cat.faq.length ? [{
        "@type": "FAQPage",
        "@id": `${site}${path}#faq`,
        url: `${site}${path}#category-faq-title`,
        name: `${cat.pageTitle.en} — Frequently asked questions`,
        mainEntity: cat.faq.map((item) => ({
          "@type": "Question",
          name: item.q.en,
          acceptedAnswer: { "@type": "Answer", text: item.a.en }
        }))
      }] : [])
    ]
  };

  return {
    file: `categories/${cat.id}/index.html`,
    path,
    html: doc(m, { path, title, description, jsonld, current: "categories" }, body, "page-category")
  };
}

/* ---------------------------------------------------------
   CONTENT PAGES (about / privacy / terms)
--------------------------------------------------------- */
export function contentPage(m, key) {
  const c = contentPages[key];
  const { i18n: { bi, t, tx }, config } = m;
  const site = config.siteUrl;
  const title = `${joinTitle(m, c.title)} — Wishora`;
  const description = m.langs.map((l) => c.meta[l]).reverse().join(" · ");
  const crumbs = [
    { label: { bn: tx("crumbHome", "bn"), en: tx("crumbHome", "en") }, href: "/", path: "/" },
    { label: c.title, path: c.path }
  ];

  const blocks = c.blocks
    .map((b) => {
      if (b.h2) return `<h2${b.id ? ` id="${b.id}"` : ""}>${bi(b.h2)}</h2>`;
      if (b.p) {
        const link = b.link ? `\n      <p><a class="text-link" href="${b.link.href}">${bi(b.link.label)} →</a></p>` : "";
        return `<p>${bi(b.p)}</p>${link}`;
      }
      if (b.ul) return `<ul class="prose-list">\n${b.ul.map((li) => `        <li>${bi(li)}</li>`).join("\n")}\n      </ul>`;
      if (b.contact) {
        return `<div class="contact-box" id="contactBox">
        <p data-contact-empty>${bi(b.contact.empty)}</p>
        <p data-contact-filled hidden>${bi(b.contact.lead)} <a class="text-link" id="contactLink"></a></p>
      </div>`;
      }
      return "";
    })
    .join("\n      ");

  const body = `<main id="main-content">
  <section class="page-hero page-hero-compact">
    <div class="hero-glow hero-glow-a" aria-hidden="true"></div>
    <div class="container">
      ${breadcrumb(m, crumbs)}
      <h1 class="page-title">${bi(c.title)}</h1>
    </div>
  </section>
  <section class="prose-section">
    <div class="container prose">
      ${key !== "about" ? `<p class="prose-updated">${m.i18n.t("pageUpdated")}: <time datetime="${UPDATED}">${UPDATED}</time></p>` : ""}
      ${blocks}
    </div>
  </section>
  ${adSlot("AD_SLOT_BOTTOM")}
</main>`;

  const jsonld = {
    "@context": "https://schema.org",
    "@graph": [
      siteLd(m),
      {
        "@type": "WebPage",
        "@id": `${site}${c.path}#webpage`,
        url: `${site}${c.path}`,
        name: c.title.en,
        description: c.meta.en,
        isPartOf: { "@id": `${site}/#website` },
        inLanguage: m.langs,
        breadcrumb: { "@id": `${site}${c.path}#breadcrumb` }
      },
      { ...breadcrumbLd(m, crumbs), "@id": `${site}${c.path}#breadcrumb` }
    ]
  };

  return {
    file: c.file,
    path: c.path,
    html: doc(m, { path: c.path, title, description, jsonld, current: key === "about" ? "about" : "" }, body, "page-content")
  };
}


const GENERATED = "<!-- GENERATED by `node scripts/build.mjs` from data/*.js — do not edit by hand. -->";

export function doc(m, p, body, bodyClass) {
  return `<!DOCTYPE html>
<html lang="${m.config.defaultLang}">
<head>
${head(m, p)}
</head>
${GENERATED}
<body class="${bodyClass}">
<a href="#main-content" class="skip-link">${m.i18n.t("skip")}</a>
${header(m, p.current)}
${body}
${footer(m)}
<script src="/config/site.js" defer></script>
${(p.extraScripts || []).map((src) => `<script src="${src}" defer></script>`).join("\n")}
<script src="/js/app.js" defer></script>
</body>
</html>
`;
}

const bothLangs = (m, fn) => Object.fromEntries(m.langs.map((l) => [l, fn(l)]));
const joinTitle = (m, obj) => m.langs.map((l) => obj[l]).join(" | ");

